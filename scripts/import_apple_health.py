"""Turn extract_apple_health.py output into an idempotent D1 SQL file.

usage: python3 -I scripts/import_apple_health.py health.json existing.json out.sql [--from 2026-01-01] [--runs-only]
existing.json = remote runs: [{id, run_date, start_time, hk_start, n_splits}]
--runs-only: write runs/splits/streams only (no other_activities, daily_metrics, running_years) — for backfills.
"""
import json, sys, os
from datetime import datetime
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import health_calc as hc

src, existing_path, out = sys.argv[1:4]
FROM = sys.argv[sys.argv.index("--from") + 1] if "--from" in sys.argv else "2026-01-01"
RUNS_ONLY = "--runs-only" in sys.argv
data = json.load(open(src))
existing = json.load(open(existing_path))
FMT = "%Y-%m-%d %H:%M:%S %z"


def q(v):
    if v is None: return "NULL"
    if isinstance(v, (int, float)): return repr(round(v, 3)) if isinstance(v, float) else str(v)
    return "'" + str(v).replace("'", "''") + "'"


def km_of(w): return float(w.get("DistanceWalkingRunning", {}).get("sum") or 0)
def stat(w, k, f="average"):
    v = w.get(k, {}).get(f)
    return float(v) if v else None


def title(hhmm):
    h = int(hhmm[:2])
    return ("Morning" if h < 11 else "Lunch" if h < 14 else "Afternoon" if h < 17 else "Evening") + " Run"


def weather(w):
    m = w["meta"]; t = m.get("HKWeatherTemperature"); h = m.get("HKWeatherHumidity")
    tc = None
    if t:
        val, unit = t.split()[0], t.split()[-1]
        tc = (float(val) - 32) * 5 / 9 if unit == "degF" else float(val)
    return (round(tc, 1) if tc is not None else None), (round(float(h.split()[0]) / 100) if h else None)


def dedupe(ws):
    """Same run recorded by several apps: keep the Apple Watch one with heart-rate data."""
    out = []
    for w in sorted(ws, key=lambda x: x["start"]):
        t = datetime.strptime(w["start"], FMT)
        dup = next((o for o in out if abs((datetime.strptime(o["start"], FMT) - t).total_seconds()) < 180), None)
        score = lambda x: ("Watch" in (x["source"] or "")) * 2 + bool(stat(x, "HeartRate"))
        if dup is None: out.append(w)
        elif score(w) > score(dup): out[out.index(dup)] = w
    return out


sql = ["-- Apple Health import (generated by scripts/import_apple_health.py). Safe to re-run."]
runs = dedupe([w for w in data["workouts"] if w["type"] == "Running" and w["start"][:10] >= FROM and km_of(w) >= 1.0])
by_hk = {e.get("hk_start"): e for e in existing if e.get("hk_start")}
by_dt = {(e["run_date"], e["start_time"]): e for e in existing}
next_id = max([e["id"] for e in existing] + [0]) + 1
stats = {"new": 0, "updated": 0, "streams": 0}

for w in runs:
    date, hhmm = w["start"][:10], w["start"][11:16]
    km = round(km_of(w), 2); dur = round(w["duration_min"] * 60)
    tc, hum = weather(w)
    dyn = w.get("dyn", {})
    speed_ms = dyn.get("RunningSpeed", 0) * 0.44704
    cadence = round(speed_ms / dyn["RunningStrideLength"] * 60) if speed_ms and dyn.get("RunningStrideLength") else None
    if cadence is not None and not 140 <= cadence <= 200: cadence = None  # averages that include walking are meaningless
    dense = len(w.get("hr", [])) >= 50 and len(w.get("dist", [])) >= 50
    pts = hc.cumulative(w["dist"], km) if dense else None
    cad = hc.cadence_bins(w.get("steps", []), dur) if dense else None  # step-based cadence beats speed / stride averages
    cs = hc.cadence_summary(cad, pts, dur) if cad else None
    if cs and cs["cad"]: cadence = cs["cad"]
    st = hc.stream(pts, w["hr"], dur, cad=cad) if dense else None
    fields = {
        "hk_start": w["start"], "indoor": 1 if w["meta"].get("HKIndoorWorkout") == "1" else 0,
        "temp_c": tc, "humidity": hum,
        "power_w": round(dyn["RunningPower"], 1) if dyn.get("RunningPower") else None,
        "stride_m": round(dyn["RunningStrideLength"], 2) if dyn.get("RunningStrideLength") else (cs or {}).get("stride"),
        "steps": (cs or {}).get("steps"),
        "vert_osc_cm": round(dyn["RunningVerticalOscillation"], 1) if dyn.get("RunningVerticalOscillation") else None,
        "gct_ms": round(dyn["RunningGroundContactTime"]) if dyn.get("RunningGroundContactTime") else None,
    }
    # Runs sent by the run Shortcut start a few minutes early (the Watch records before the workout starts): allow 15 min.
    tol = lambda e: 15 if e.get("source") == "shortcut" else 3
    match = by_hk.get(w["start"]) or next((e for (d, t), e in by_dt.items() if d == date and t and abs(int(t[:2]) * 60 + int(t[3:]) - int(hhmm[:2]) * 60 - int(hhmm[3:])) <= tol(e)), None)
    if match and match.get("source") == "shortcut":
        # The export has the exact workout: replace the Shortcut estimate (UPDATE keeps the run id, so analyses stay linked).
        rid = match["id"]; stats["updated"] += 1
        hr_avg = stat(w, "HeartRate"); hr_max = stat(w, "HeartRate", "maximum"); kcal = stat(w, "ActiveEnergyBurned", "sum")
        row = {"start_time": hhmm, "distance_km": km, "moving_time_s": dur, "elapsed_time_s": dur, "avg_pace_s": round(dur / km),
               "avg_hr": round(hr_avg) if hr_avg else None, "max_hr": round(hr_max) if hr_max else None,
               "calories": round(kcal) if kcal else None, "cadence_spm": cadence, "source": "apple_health", **fields}
        sql.append(f"UPDATE runs SET {', '.join(f'{k} = {q(v)}' for k, v in row.items())} WHERE id = {rid};")
        have_splits = False
    elif match:
        rid = match["id"]; stats["updated"] += 1
        sets = ", ".join(f"{k} = {q(v)}" for k, v in fields.items())
        new_cad = f"{cadence}" if cs and cs["cad"] else f"COALESCE(cadence_spm, {q(cadence)})"
        sets = sets.replace(f"steps = {q(fields['steps'])}", f"steps = COALESCE(steps, {q(fields['steps'])})")
        sets += f", cadence_spm = {new_cad}, max_hr = COALESCE(max_hr, {q(round(stat(w, 'HeartRate', 'maximum')) if stat(w, 'HeartRate', 'maximum') else None)})"
        sql.append(f"UPDATE runs SET {sets} WHERE id = {rid};")
        have_splits = match.get("n_splits", 0) > 0
    else:
        rid = next_id; next_id += 1; stats["new"] += 1
        hr_avg = stat(w, "HeartRate"); hr_max = stat(w, "HeartRate", "maximum")
        kcal = stat(w, "ActiveEnergyBurned", "sum")
        run_type = ("runwalk" if hc.walk_share(st["v"]) > 0.08 else "easy") if st else None
        row = {"id": rid, "run_date": date, "start_time": hhmm, "title": title(hhmm), "run_type": run_type,
               "distance_km": km, "moving_time_s": dur, "elapsed_time_s": dur, "avg_pace_s": round(dur / km),
               "avg_hr": round(hr_avg) if hr_avg else None, "max_hr": round(hr_max) if hr_max else None,
               "calories": round(kcal) if kcal else None, "cadence_spm": cadence, "device": "Apple Watch",
               "source": "apple_health", **fields}
        cols = ", ".join(row); vals = ", ".join(q(v) for v in row.values())
        sql.append(f"INSERT OR REPLACE INTO runs ({cols}) VALUES ({vals});")
        have_splits = False
    if dense and not have_splits:
        sql.append(f"DELETE FROM splits WHERE run_id = {rid};")
        for s in hc.splits(pts, w["hr"], km, cad):
            sql.append(f"INSERT INTO splits (run_id, split_no, distance_km, pace_s, avg_hr, cadence_spm) VALUES ({rid}, {s['n']}, {s['km']}, {s['pace']}, {q(s['hr'])}, {q(s['cad'])});")
    elif dense and cad:  # keep the existing (Strava) splits, add cadence per km
        for s in hc.splits(pts, w["hr"], km, cad):
            sql.append(f"UPDATE splits SET cadence_spm = {q(s['cad'])} WHERE run_id = {rid} AND split_no = {s['n']};")
    if st:
        stats["streams"] += 1
        sql.append(f"INSERT OR REPLACE INTO run_streams (run_id, points) VALUES ({rid}, {q(json.dumps(st, separators=(',', ':')))});")

# other workouts (strength, walks, rides...) → other_activities with negative ids (Strava ids are positive)
others = 0
for w in ([] if RUNS_ONLY else data["workouts"]):
    if w["type"] == "Running" or w["start"][:10] < FROM: continue
    t = datetime.strptime(w["start"], FMT)
    hr_avg = stat(w, "HeartRate"); km = km_of(w) or stat(w, "DistanceCycling", "sum")
    sql.append("INSERT OR REPLACE INTO other_activities (strava_id, activity_date, start_time, sport_type, name, moving_time_s, distance_km, avg_hr) VALUES "
               f"({-int(t.timestamp())}, {q(w['start'][:10])}, {q(w['start'][11:16])}, {q(w['type'])}, {q(w['type'])}, {round(w['duration_min'] * 60)}, {q(round(km, 2) if km else None)}, {q(round(hr_avg) if hr_avg else None)});")
    others += 1

for r in ([] if RUNS_ONLY else data["daily"]):
    cols = list(r)
    sql.append(f"INSERT OR REPLACE INTO daily_metrics ({', '.join(cols)}) VALUES ({', '.join(q(r[c]) for c in cols)});")

# running history by year (all time)
years = {}
for w in dedupe([w for w in data["workouts"] if w["type"] == "Running" and km_of(w) >= 0.3 and "2000" < w["start"][:4]]):
    y = int(w["start"][:4]); k = km_of(w); s = w["duration_min"] * 60
    e = years.setdefault(y, {"runs": 0, "km": 0, "long": None, "best": None})
    e["runs"] += 1; e["km"] += k
    if not e["long"] or k > e["long"][0]: e["long"] = (k, w["start"][:10], round(s))
    if k >= 3 and (e["best"] is None or s / k < e["best"]): e["best"] = s / k
for y, e in ([] if RUNS_ONLY else sorted(years.items())):
    sql.append(f"INSERT OR REPLACE INTO running_years (year, runs, km, longest_km, longest_date, longest_time_s, best_pace_s) VALUES "
               f"({y}, {e['runs']}, {round(e['km'], 1)}, {round(e['long'][0], 2)}, {q(e['long'][1])}, {e['long'][2]}, {q(round(e['best']) if e['best'] else None)});")

open(out, "w").write("\n".join(sql) + "\n")
print(stats, "others", others, "daily", len(data["daily"]), "years", len(years), "→", out)
